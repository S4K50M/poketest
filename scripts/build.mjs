import { build, context } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root=fileURLToPath(new URL('..',import.meta.url));
const options={
  absWorkingDir:root,
  entryPoints:['src/main.js'],
  outfile:'bundle/game.js',
  bundle:true,
  format:'iife',
  target:'es2020',
  banner:{js:'// Generated by npm run build. Edit src/ files, then rebuild.'},
};

if(process.argv.includes('--watch')){
  const session=await context(options);
  await session.watch();
  await import('../server.mjs');
  console.log('Watching source files; browser bundle rebuilds automatically.');
}else if(process.argv.includes('--check')){
  const result=await build({...options,write:false});
  const saved=await readFile(new URL('../bundle/game.js',import.meta.url),'utf8').catch(()=>'');
  if(saved!==result.outputFiles[0].text){
    console.error('Browser bundle is missing or out of date. Run npm run build.');
    process.exitCode=1;
  }else console.log('Browser bundle matches source.');
}else{
  await build(options);
  console.log('Built bundle/game.js for both direct file opening and HTTP hosting.');
}
